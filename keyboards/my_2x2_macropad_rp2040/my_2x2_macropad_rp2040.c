#pragma region LED Configurations

#define TOTAL_LED_COUNT 3
#define LED_LAYER_0 GP18
#define LED_LAYER_1 GP19
#define LED_LAYER_2 GP20

static pin_t led_pins[TOTAL_LED_COUNT] = { LED_LAYER_0, LED_LAYER_1, LED_LAYER_2 };

// This function will turn on all LED's
void turn_on_all_leds(void) {
    for (uint8_t i = 0; i < TOTAL_LED_COUNT; i++) {
        gpio_write_pin_high(led_pins[i]);   // This will turn on a led.
    }
}

// This function will turn off all LRD's
void turn_off_all_leds(void) {
    for (uint8_t i = 0; i < TOTAL_LED_COUNT; i++) {
        gpio_write_pin_low(led_pins[i]);   // This will turn on a led.
    }
}

void update_led_for_layer(uint8_t layer) {
    turn_off_all_leds();
    if (layer < TOTAL_LED_COUNT) {
        gpio_write_pin_high(led_pins[layer]);
    }
}

void keyboard_post_init_kb(void) {
    for (uint8_t i = 0; i < TOTAL_LED_COUNT; i++) {
        gpio_set_pin_output(led_pins[i]);
        gpio_write_pin_low(led_pins[i]);
    }

    turn_on_all_leds();
    wait_ms(500);   // keep LED's ON for 500 milliseconds, which means 0.5 seconds
    turn_off_all_leds();

    update_led_for_layer(0);    // Turn on default layer LED
    keyboard_post_init_user();
}
