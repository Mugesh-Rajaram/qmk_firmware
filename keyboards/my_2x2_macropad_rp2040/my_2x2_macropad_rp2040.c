bool oled_task_kb(void) {
    if (!oled_task_user()) {
        return false;
    }

    static bool logo_rendered = false;
    if (!logo_rendered) {
        render_logo();
        if (timer_read() > 2500)
            logo_rendered = true;
    }
    else {
        switch(current_display_mode) {
            case 0:
                render_layers();
                break;
            // case 1:
            //     render_animation();
            //     break;
            // case 2:
            //     render_button_pressed();
            //     break;
        }
    }
    return false;
}

void oled_display_mode_step(void) {
    current_display_mode = (current_display_mode + 1) % 3;
}

// when the layer is changed, flash the layer number on the screen
layer_state_t layer_state_set_kb(layer_state_t state) {
    flash_timer = timer_read();
    layer_changed = true;

    //Turn layer indication ON LED based on selected layer
    uint8_t current_layer = get_highest_layer(state);
    update_led_for_layer(current_layer);

    return layer_state_set_user(state);
}
